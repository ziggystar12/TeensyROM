import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const tables=fs.readFileSync(path.join(root,'vm/video/rad_f1_tables.h'),'utf8');
const p=tables.match(/pepto\[16\]\[3\] = ([\s\S]*?);/)[1].match(/0x[0-9a-f]+/gi).map(Number);
const gamma=Math.fround(0.96111111111);
const tone=Array.from({length:16},(_,i)=>Math.trunc(Math.fround(Math.fround(Math.pow(Math.fround(((i*16*350)>>8)/255),gamma))*255)));
const lut=[];
for(let r=0;r<16;r++)for(let g=0;g<16;g++)for(let b=0;b<16;b++){
 let best=Infinity,index=0;
 for(let c=0;c<16;c++){
  const error=(tone[r]-p[c*3])**2+(tone[g]-p[c*3+1])**2+(tone[b]-p[c*3+2])**2;
  if(error<best){best=error;index=c;}
 }lut.push(index);
}
const file=path.join(root,'vm/video/rad_f1_lut.h');
const rows=Array.from({length:128},(_,i)=>'    '+lut.slice(i*32,i*32+32).join(',')+',');
const content='// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by scripts/generate-rad-f1-lut.mjs from RAD-Doom preset 0.\n// Copyright (c) 2022, 2023 Carsten Dachsbacher; MHS adaptation 2026.\n#pragma once\n#include "rad_f1_tables.h"\nnamespace mpe_video { namespace rad_f1 {\nstatic constexpr uint8_t rgbToVic[4096] MPE_VIDEO_RAD_RODATA ={\n'+rows.join('\n')+'\n};\n}}\n';
if(process.argv.includes('--check')){
 if(fs.readFileSync(file,'utf8')!==content)throw Error('RAD F1 LUT differs from generator');
}else fs.writeFileSync(file,content);
console.log('RAD F1: 4096-byte immutable RGB lookup verified/generated');
